#!/usr/bin/env python3
"""Generate RadioMusic32/SincTable.h: polyphase windowed-sinc interpolator.

16 taps, 512 fractional phases, Q15. Each phase is normalised to unity DC gain
so stepping through phases doesn't modulate the level.
Run: python3 tools/gen_sinc_table.py > RadioMusic32/SincTable.h
"""
import math

TAPS = 16
PHASES = 512
CUTOFF = 0.47   # fraction of the input sample rate
BETA = 7.0      # Kaiser window, ~70 dB stopband


def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


def tap(t):
    half = TAPS / 2
    if abs(t) >= half:
        return 0.0
    w = i0(BETA * math.sqrt(1 - (t / half) ** 2)) / i0(BETA)
    x = 2 * CUTOFF * t
    s = 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)
    return 2 * CUTOFF * s * w


print("#ifndef SincTable_h")
print("#define SincTable_h")
print()
print("// Generated by tools/gen_sinc_table.py - do not edit.")
print(f"// {TAPS}-tap Kaiser-windowed sinc (beta {BETA}, cutoff {CUTOFF} fs), {PHASES} phases, Q15.")
print("// Row p interpolates at position 7 + p/PHASES in a window of TAPS samples, oldest first.")
print()
print(f"#define SINC_TAPS   {TAPS}")
print(f"#define SINC_PHASES {PHASES}")
print()
print("static const int16_t sincTable[SINC_PHASES][SINC_TAPS] = {")
for p in range(PHASES):
    mu = p / PHASES
    h = [tap(k - (TAPS // 2 - 1) - mu) for k in range(TAPS)]
    g = sum(h)
    q = [round(v / g * 32768) for v in h]
    # put rounding error on the largest tap so each row sums to exactly 32768
    q[max(range(TAPS), key=lambda k: abs(q[k]))] += 32768 - sum(q)
    assert all(-32768 <= v <= 32767 for v in q)
    print("\t{" + ",".join(str(v) for v in q) + "},")
print("};")
print()
print("#endif")
